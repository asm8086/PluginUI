using System.ComponentModel;

namespace PluginUI;

/// <summary>Look of a vector <see cref="Knob"/>.</summary>
public enum KnobStyle
{
    /// <summary>Value arc around a flat cap with a pointer line (modern plug-in look).</summary>
    Arc,
    /// <summary>Raised, shaded body with tick marks and a pointer dot (hardware look).</summary>
    Classic,
    /// <summary>Arcs and pointer only, no body.</summary>
    Minimal,
}

/// <summary>Mouse movement that drives a drag control.</summary>
public enum DragDirection
{
    /// <summary>Up increases.</summary>
    Vertical,
    /// <summary>Right increases.</summary>
    Horizontal,
    /// <summary>Up or right increases (both axes add up).</summary>
    Both,
}

/// <summary>
/// Rotary control. Drag up/right to increase (Shift = fine), wheel and arrow keys step, double-click or Ctrl+click
/// resets, Alt+click (or right double-click) types a value. Vector styles: <see cref="KnobStyle"/>; bitmap/SVG looks
/// through <see cref="Control.Skin"/> (<see cref="FilmStripSkin"/>, <see cref="SvgRotarySkin"/>).
/// </summary>
/// <example>
/// Bound to a parameter, with the classic vector look, then with a film strip skin (128 frames stacked vertically):
/// <code>
/// var cutoff = new Knob(Parameters[model.Cutoff]) { Label = "CUTOFF", KnobStyle = KnobStyle.Classic, ShowValueBubble = true };
/// var drive = new Knob(Parameters[model.Drive])
/// {
///     Label = "DRIVE",
///     // Resource embedded with LogicalName="assets/knob.png" (as in projects generated by PluginUIEditor).
///     Skin = new FilmStripSkin(new FilmStrip(ImageSource.FromResource(typeof(MyEditor).Assembly, "assets/knob.png"), 128, Orientation.Vertical)),
/// };
/// </code>
/// </example>
public class Knob : ValueControl
{
    private KnobStyle _knobStyle = KnobStyle.Arc;
    private bool _bipolar;
    private double _modulation;
    private RotaryLinearHelpers.DragAccumulator _drag;

    /// <summary>Creates a knob.</summary>
    public Knob()
    {
        Cursor = StandardCursor.SizeNS;
    }

    /// <summary>Creates a knob bound to a parameter.</summary>
    public Knob(IParameter parameter) : this() => Parameter = parameter;

    /// <summary>Vector look.</summary>
    [Category("Appearance")]
    public KnobStyle KnobStyle { get => _knobStyle; set { _knobStyle = value; InvalidateVisual(); } }

    /// <summary>Angle at value 0 (degrees, clockwise from 12 o'clock).</summary>
    [Category("Data")]
    public float MinAngle { get; set; } = -135f;

    /// <summary>Angle at value 1.</summary>
    [Category("Data")]
    public float MaxAngle { get; set; } = 135f;

    /// <summary>Draws the value arc from <see cref="BipolarCenter"/> (pan, balance, ± gain).</summary>
    [Category("Value")]
    public bool IsBipolar { get => _bipolar; set { _bipolar = value; InvalidateVisual(); } }

    /// <summary>Origin of the bipolar arc (normalized).</summary>
    [Category("Value")]
    public double BipolarCenter { get; set; } = 0.5;

    /// <summary>
    /// Signed modulation depth (normalized, −1..1) drawn as a second arc from the value: shows LFO/envelope
    /// modulation without changing the value. 0 hides it.
    /// </summary>
    [Category("Value")]
    public double ModulationAmount { get => _modulation; set { _modulation = Math.Clamp(value, -1.0, 1.0); InvalidateVisual(); } }

    /// <summary>Color of the modulation arc (null = palette alternate accent).</summary>
    [Category("Appearance")]
    public Color? ModulationColor { get; set; }

    /// <summary>Number of tick marks around the knob (0 = none; <see cref="KnobStyle.Classic"/> defaults to 11).</summary>
    [Category("Appearance")]
    public int TickCount { get; set; } = -1;

    /// <summary>Mouse axis driving the drag.</summary>
    [Category("Behavior")]
    public DragDirection DragDirection { get; set; } = DragDirection.Both;

    /// <summary>
    /// Allows typing the value in a text box (default <c>true</c>). The actions that open it are chosen by
    /// <see cref="ValueControl.TextEntryTriggers"/>: by default a double-click on the value text, Alt+click,
    /// a right double-click or Enter.
    /// </summary>
    [Category("Behavior")]
    public bool AllowTextEntry { get; set; } = true;

    /// <inheritdoc />
    protected override bool SupportsTextEntry => AllowTextEntry;

    /// <summary>Text → normalized value parser for typed values (default: parameter parser, or percent).</summary>
    [Browsable(false)]
    public Func<string, double?>? Parser { get; set; }

    /// <inheritdoc />
    protected override Size DefaultSize => new(56f, 76f);

    /// <summary>Angle (degrees) of a normalized value.</summary>
    public float AngleOf(double normalized) => MinAngle + (MaxAngle - MinAngle) * (float)Math.Clamp(normalized, 0.0, 1.0);

    // ---------------------------------------------------------------- rendering

    /// <inheritdoc />
    protected override void RenderVector(DrawingContext dc, Rect widget, VectorStyle style)
    {
        var square = widget.CenteredSquare();
        float size = square.Width;
        if (size < 8f) return;
        var c = square.Center;
        float track = MathF.Max(2f, MathF.Min(style.TrackThickness, size * 0.09f));
        float arcRadius = size * 0.5f - track * 0.5f - 1f;
        var p = Theme.Palette;
        float value = (float)Value;
        float angle = AngleOf(value);
        float origin = AngleOf(_bipolar ? BipolarCenter : 0.0);
        var accent = style.Accent;
        bool hot = IsMouseOver || IsPressed;
        int ticks = TickCount >= 0 ? TickCount : _knobStyle == KnobStyle.Classic ? 11 : 0;

        switch (_knobStyle)
        {
            case KnobStyle.Classic:
            {
                float tickOuter = size * 0.5f - 0.5f;
                float tickInner = tickOuter - MathF.Max(2.5f, size * 0.06f);
                DrawTicks(dc, c, tickInner, tickOuter, ticks, style.LabelColor.Fade(0.8f));
                float body = tickInner - MathF.Max(2f, size * 0.05f);
                // Value ring just inside the ticks.
                RotaryLinearHelpers.StrokeArc(dc, c, body + 0.5f, MinAngle, MaxAngle - MinAngle, p.Track, 2f, StrokeStyle.Solid);
                RotaryLinearHelpers.StrokeArc(dc, c, body + 0.5f, origin, angle - origin, accent, 2f, StrokeStyle.Solid);
                float r = body - 2.5f;
                if (style.DrawShadow) dc.DrawShadow(Rect.FromCenter(c, r * 2f, r * 2f), r, style.ShadowBlur, new Point(0f, style.ShadowOffset), style.Shadow.Fade(0.8f));
                var fill = IsPressed ? style.Pressed : style.Fill;
                dc.FillCircle(c, r, new RadialGradientPaint(new Point(0.5f, 0.5f), 0.5f, 0.5f,
                    [new(0f, fill.Lighten(0.10f)), new(0.85f, fill), new(1f, fill.Darken(0.25f))], new Point(-0.18f, -0.22f)));
                if (hot) dc.FillCircle(c, r, style.Hover);
                if (style.DrawFrame) dc.DrawCircle(c, r - style.FrameThickness * 0.5f, style.Frame, style.FrameThickness);
                var dot = PathGeometry.PointOnCircle(c, r * 0.68f, angle);
                dc.FillCircle(dot, MathF.Max(1.8f, r * 0.11f), accent);
                break;
            }
            case KnobStyle.Minimal:
            {
                DrawTicks(dc, c, arcRadius + track * 0.5f + 1f, arcRadius + track * 0.5f + 3.5f, ticks, style.LabelColor.Fade(0.6f));
                RotaryLinearHelpers.StrokeArc(dc, c, arcRadius, MinAngle, MaxAngle - MinAngle, p.Track, track);
                RotaryLinearHelpers.StrokeArc(dc, c, arcRadius, origin, angle - origin, hot ? accent.Lighten(0.12f) : accent, track);
                DrawModulation(dc, c, arcRadius, track, value);
                var a = PathGeometry.PointOnCircle(c, arcRadius * 0.15f, angle);
                var b = PathGeometry.PointOnCircle(c, arcRadius - track * 1.2f, angle);
                dc.DrawLine(a, b, style.ValueColor, MathF.Max(1.5f, size * 0.04f), StrokeStyle.Round);
                break;
            }
            default:
            {
                DrawTicks(dc, c, arcRadius + track * 0.5f + 1f, arcRadius + track * 0.5f + 3.5f, ticks, style.LabelColor.Fade(0.6f));
                RotaryLinearHelpers.StrokeArc(dc, c, arcRadius, MinAngle, MaxAngle - MinAngle, p.Track, track);
                RotaryLinearHelpers.StrokeArc(dc, c, arcRadius, origin, angle - origin, accent, track);
                DrawModulation(dc, c, arcRadius, track, value);
                float r = arcRadius - track * 0.5f - MathF.Max(2.5f, size * 0.07f);
                if (r > 3f)
                {
                    if (style.DrawShadow) dc.DrawShadow(Rect.FromCenter(c, r * 2f, r * 2f), r, style.ShadowBlur, new Point(0f, style.ShadowOffset), style.Shadow);
                    var fill = IsPressed ? style.Pressed : style.Fill;
                    dc.FillCircle(c, r, Paint.Vertical(fill.Lighten(0.06f), fill.Darken(0.06f)));
                    if (hot) dc.FillCircle(c, r, style.Hover);
                    if (style.DrawFrame) dc.DrawCircle(c, r - style.FrameThickness * 0.5f, style.Frame, style.FrameThickness);
                    var a = PathGeometry.PointOnCircle(c, r * 0.35f, angle);
                    var b = PathGeometry.PointOnCircle(c, r * 0.88f, angle);
                    dc.DrawLine(a, b, style.ValueColor, MathF.Max(1.5f, size * 0.045f), StrokeStyle.Round);
                }
                break;
            }
        }
    }

    private void DrawTicks(DrawingContext dc, Point c, float inner, float outer, int count, Color color)
    {
        if (count < 2) return;
        for (int i = 0; i < count; i++)
        {
            float a = MinAngle + (MaxAngle - MinAngle) * i / (count - 1);
            dc.DrawLine(PathGeometry.PointOnCircle(c, inner, a), PathGeometry.PointOnCircle(c, outer, a), color, 1f, StrokeStyle.Round);
        }
    }

    private void DrawModulation(DrawingContext dc, Point c, float radius, float track, float value)
    {
        if (Math.Abs(_modulation) < 1e-4) return;
        float end = (float)Math.Clamp(value + _modulation, 0.0, 1.0);
        var color = ModulationColor ?? Theme.Palette.AccentAlt;
        float r = radius - track - 1.5f;
        RotaryLinearHelpers.StrokeArc(dc, c, r, AngleOf(value), AngleOf(end) - AngleOf(value), color, MathF.Max(1.5f, track * 0.5f));
    }

    // ---------------------------------------------------------------- input

    /// <inheritdoc />
    protected internal override void OnMouseDown(MouseEventArgs e)
    {
        base.OnMouseDown(e);
        if (e.Handled || !IsEffectivelyEnabled) return;
        if (TryHandleTextEntry(e)) return;
        if (e.Button != MouseButton.Left) return;
        if (TryHandleReset(e)) return;
        IsPressed = true;
        _drag.Start(e.Position, Value);
        BeginGesture();
        e.Handled = true;
        InvalidateVisual();
    }

    /// <inheritdoc />
    protected internal override void OnMouseMove(MouseEventArgs e)
    {
        base.OnMouseMove(e);
        if (!IsPressed) return;
        float kx = DragDirection == DragDirection.Vertical ? 0f : 1f;
        float ky = DragDirection == DragDirection.Horizontal ? 0f : -1f;
        double factor = 1.0 / Math.Max(10f, DragSensitivity) * (e.Shift ? FineFactor : 1f);
        UpdateGesture(_drag.Move(e.Position, kx, ky, factor));
    }

    /// <inheritdoc />
    protected internal override void OnMouseUp(MouseEventArgs e)
    {
        base.OnMouseUp(e);
        if (!IsPressed || e.Button != MouseButton.Left) return;
        IsPressed = false;
        EndGesture();
        InvalidateVisual();
    }

    /// <summary>Opens the in-place text box over the value text (or over the knob when the value is hidden).</summary>
    public override void BeginTextEntry()
    {
        if (!AllowTextEntry) return;
        var style = EffectiveStyle;
        LayoutParts(style, out _, out var widget, out var valueArea);
        var area = valueArea.IsEmpty ? Rect.FromCenter(widget.Center, MathF.Max(56f, widget.Width), 20f) : valueArea;
        RotaryLinearHelpers.BeginTextEntry(this, area, ValueText ?? string.Empty, Parameter, Parser, SetValueByUser);
    }
}
