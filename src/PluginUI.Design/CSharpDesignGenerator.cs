using System.Globalization;
using System.Text;

namespace PluginUI.Design;

/// <summary>
/// Generates the <c>.Designer.cs</c> part of a partial class from a design, the way the Windows Forms designer does:
/// fields for named elements, <c>BuildDesign()</c> creating the tree, and partial methods for what only the other
/// part of the class knows (parameters, assets, event wiring).
/// </summary>
/// <remarks>
/// <para>Generated members:</para>
/// <list type="bullet">
/// <item><c>DesignSize</c>, <c>DesignSizing</c> and <c>CreateDesignTheme()</c>;</item>
/// <item>one field per named element;</item>
/// <item><c>BuildDesign()</c>, and <c>protected override UIElement Build()</c> for plug-in editors;</item>
/// <item><c>partial void OnBuilt(UIElement root)</c>, called at the end of <c>BuildDesign()</c> (optional to implement);</item>
/// <item><c>private partial IParameter? BindParameter(string name)</c> when the design binds parameters, and
/// <c>LoadImage</c> / <c>LoadSvg</c> when it uses assets (to implement in the other part).</item>
/// </list>
/// <para>The generated code depends on PluginUI only (not on PluginUI.Design).</para>
/// </remarks>
public sealed class CSharpDesignGenerator
{
    private readonly DesignTypeRegistry _registry;
    private string? _className;
    private IReadOnlySet<string>? _reserved;
    private readonly StringBuilder _sb = new();
    private readonly List<string> _warnings = new();
    private readonly HashSet<string> _usedNames = new(StringComparer.Ordinal);
    private int _indent;

    /// <summary>Creates a generator.</summary>
    /// <param name="registry">Element types (default: <see cref="DesignTypeRegistry.Default"/>).</param>
    public CSharpDesignGenerator(DesignTypeRegistry? registry = null) => _registry = registry ?? DesignTypeRegistry.Default;

    /// <summary>Problems found by the last <see cref="Generate"/> call.</summary>
    public IReadOnlyList<string> Warnings => _warnings;

    /// <summary>Text written in the header comment (e.g. the design file name).</summary>
    public string? SourceName { get; set; }

    /// <summary>Timestamp written in the header (default: now, UTC). Set it for reproducible output.</summary>
    public DateTime? Timestamp { get; set; }

    /// <summary>Generates the file.</summary>
    /// <param name="document">The design.</param>
    /// <returns>The C# source.</returns>
    public string Generate(DesignDocument document)
    {
        ArgumentNullException.ThrowIfNull(document);
        _sb.Clear();
        _warnings.Clear();
        _usedNames.Clear();
        _fieldNodes.Clear();
        _indent = 0;
        var settings = document.Codegen;
        _className = settings.ClassName;
        _reserved = ReservedTypeNames(_registry);
        var named = document.AllNodes().Where(n => n.Name is not null).ToList();
        foreach (var n in named)
        {
            if (!IsElementName(n.Name!)) _warnings.Add($"'{n.Name}' cannot name a field (C# keyword, type name used by the generated code, or member of the class): the element is generated as a local variable.");
            else if (!_usedNames.Add(n.Name!)) _warnings.Add($"Duplicate element name '{n.Name}': the second one is generated as a local variable.");
        }
        if (ValidateCodegen(settings, _registry) is { } invalid) throw new InvalidOperationException(invalid);
        bool bindings = document.AllNodes().Any(n => n.Bindings.Count > 0);
        bool images = document.AllNodes().Any(n => n.Properties.Values.Any(v => DesignValues.UsesAssetLoader(v, DesignAssetKind.Image)));
        bool svgs = document.AllNodes().Any(n => n.Properties.Values.Any(v => DesignValues.UsesAssetLoader(v, DesignAssetKind.Svg)));

        string stamp = (Timestamp ?? DateTime.UtcNow).ToString("yyyy/MM/dd HH:mm:ss", CultureInfo.InvariantCulture);
        Line($"// {stamp} UTC - {DesignValues.CommentText(document.Name)}");
        Line("// <auto-generated>");
        Line($"//     Generated by PluginUIEditor from {DesignValues.CommentText(SourceName ?? document.Name + DesignDocument.FileExtension)}.");
        Line("//     Changes to this file are lost when the design is generated again: edit the design, or the other part");
        Line($"//     of the partial class {settings.ClassName} (OnBuilt, BindParameter, LoadImage, LoadSvg).");
        Line("// </auto-generated>");
        Line();
        Line("#nullable enable");
        Line();
        Line("using PluginUI;");
        Line();
        Line($"namespace {settings.Namespace};");
        Line();
        Line($"partial class {settings.ClassName}");
        Open();
        Line("/// <summary>Logical size of the design at 100 %.</summary>");
        Line($"public static readonly Size DesignSize = {DesignValues.ToCSharp(document.DesignSize, typeof(Size), TypeName)};");
        Line();
        Line("/// <summary>Resizing behavior of the design.</summary>");
        Line($"public const SizingMode DesignSizing = {DesignValues.ToCSharp(document.Sizing, typeof(SizingMode), TypeName)};");
        Line();
        Line("/// <summary>Creates the theme of the design.</summary>");
        Line($"public static Theme CreateDesignTheme() => {ThemeJson.ToCSharp(document.Theme, TypeName)};");
        Line();

        string access = settings.FieldAccess is "private" or "internal" or "protected" or "public" ? settings.FieldAccess : "private";
        foreach (var n in named.Where(n => IsField(n)))
        {
            var info = _registry.Find(n.Type);
            Line($"{access} {(info is null ? "UIElement" : TypeName(info.Type))} {n.Name} = null!;");
        }
        if (named.Count > 0) Line();

        string buildAccess = settings.Target == CodegenTarget.Standalone ? "public" : "private";
        Line("/// <summary>Creates the element tree of the design, then calls <see cref=\"OnBuilt\"/>.</summary>");
        Line("/// <returns>The root element.</returns>");
        Line($"{buildAccess} UIElement BuildDesign()");
        Open();
        _localCounter = 0;
        string root = EmitNode(document.Root, parent: null, parentInfo: null, index: 0);
        Line($"OnBuilt({root});");
        Line($"return {root};");
        Close();

        var fields = named.Where(n => IsField(n)).ToList();
        {
            Line();
            Line("/// <summary>");
            Line("/// Points the element fields to the elements of another tree built from the design (by name), e.g. after a");
            Line("/// live design reload. A field keeps its element when the tree has no element of that name and type.");
            Line("/// </summary>");
            Line("/// <param name=\"designTree\">Root of the new tree.</param>");
            Line("private void BindDesignFields(UIElement designTree)");
            Open();
            foreach (var n in fields)
            {
                var info = _registry.Find(n.Type);
                string type = info is null ? "UIElement" : TypeName(info.Type);
                Line($"this.{n.Name} = designTree.FindByName({DesignValues.CSharpString(n.Name!)}) as {type} ?? this.{n.Name};");
            }
            Close();
        }

        if (settings.Target == CodegenTarget.PluginEditorView && settings.GenerateBuildOverride)
        {
            Line();
            Line("/// <inheritdoc />");
            Line("protected override UIElement Build() => BuildDesign();");
        }

        Line();
        Line("/// <summary>Called at the end of <see cref=\"BuildDesign\"/>: wire events and set what the design cannot describe.</summary>");
        Line("/// <param name=\"root\">The root element (not attached to a host yet).</param>");
        Line("partial void OnBuilt(UIElement root);");
        if (bindings)
        {
            Line();
            Line("/// <summary>Returns the parameter bound to a design parameter name (implement in the other part of the class).</summary>");
            Line("/// <param name=\"name\">Design parameter name.</param>");
            Line("/// <returns>The parameter, or <c>null</c> to leave the control unbound.</returns>");
            Line("private partial IParameter? BindParameter(string name);");
        }
        if (images)
        {
            Line();
            Line("/// <summary>Loads an image of the design (implement in the other part of the class).</summary>");
            Line("/// <param name=\"path\">Asset path, relative to the design file.</param>");
            Line("/// <returns>The image.</returns>");
            Line("private partial ImageSource LoadImage(string path);");
        }
        if (svgs)
        {
            Line();
            Line("/// <summary>Loads an SVG document of the design (implement in the other part of the class).</summary>");
            Line("/// <param name=\"path\">Asset path, relative to the design file.</param>");
            Line("/// <returns>The SVG image.</returns>");
            Line("private partial SvgImage LoadSvg(string path);");
        }
        Close();
        return _sb.ToString();
    }

    private int _localCounter;
    private readonly HashSet<DesignNode> _fieldNodes = new(ReferenceEqualityComparer.Instance);

    private bool IsField(DesignNode node)
    {
        if (node.Name is null || !IsElementName(node.Name)) return false;
        // The first node with a given name owns the field.
        foreach (var other in _fieldNodes) if (other.Name == node.Name) return ReferenceEquals(other, node);
        _fieldNodes.Add(node);
        return true;
    }

    private string EmitNode(DesignNode node, string? parent, DesignTypeInfo? parentInfo, int index, DesignNode? parentNode = null)
    {
        var info = _registry.Find(node.Type);
        if (info is null)
        {
            _warnings.Add($"Unknown element type '{node.Type}': generated as an empty Canvas.");
        }
        bool field = IsField(node);
        string variable = field ? node.Name! : NextLocal(info?.Type.Name ?? "element");
        string typeName = info is null ? "Canvas" : TypeName(info.Type);

        var initializers = new List<string>();
        if (node.Name is not null) initializers.Add($"Name = {DesignValues.CSharpString(node.Name)}");
        var statements = new List<string>();
        foreach (var (name, value) in node.Properties)
        {
            var property = info?.Find(name);
            if (property is null || property.IsBinding)
            {
                if (info is not null) _warnings.Add($"{variable}: {node.Type} has no property '{name}' (skipped).");
                continue;
            }
            if (property.Property is null)
            {
                // Virtual properties: the rows and columns of a Grid.
                if (name is "Rows" or "Columns" && value is string lengths)
                {
                    string list = name == "Rows" ? "RowDefinitions" : "ColumnDefinitions";
                    foreach (var part in lengths.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                    {
                        // Checked now: the loader skips an invalid length with a warning, the generated code must not throw.
                        try
                        {
                            GridLength.Parse(part);
                        }
                        catch (FormatException)
                        {
                            _warnings.Add($"{variable}.{name}: invalid grid length '{part}' (skipped).");
                            continue;
                        }
                        statements.Add($"{variable}.{list}.Add(GridLength.Parse({DesignValues.CSharpString(part)}));");
                    }
                }
                continue;
            }
            try
            {
                initializers.Add($"{name} = {DesignValues.ToCSharp(value, property.PropertyType, TypeName)}");
            }
            catch (NotSupportedException e)
            {
                _warnings.Add($"{variable}.{name}: {e.Message}");
            }
        }
        foreach (var (name, parameter) in node.Bindings)
        {
            if (info?.Find(name) is not { IsBinding: true })
            {
                _warnings.Add($"{variable}: {node.Type} has no parameter property '{name}' (skipped).");
                continue;
            }
            statements.Add($"{variable}.{name} = BindParameter({DesignValues.CSharpString(parameter)});");
        }
        foreach (var n in node.UnknownProperties.Keys.Where(k => !node.Properties.ContainsKey(k)))
        {
            _warnings.Add($"{variable}: unknown property '{n}' (skipped).");
        }

        string declaration = field ? variable : "var " + variable;
        if (initializers.Count == 0)
        {
            Line($"{declaration} = new {typeName}();");
        }
        else if (initializers.Count <= 2 && initializers.Sum(i => i.Length) < 70)
        {
            Line($"{declaration} = new {typeName} {{ {string.Join(", ", initializers)} }};");
        }
        else
        {
            Line($"{declaration} = new {typeName}");
            Line("{");
            _indent++;
            foreach (var i in initializers) Line(i + ",");
            _indent--;
            Line("};");
        }
        foreach (var s in statements) Line(s);

        if (parent is not null && parentInfo is not null) EmitAdd(parent, parentInfo, parentNode!, node, variable, index);

        for (int i = 0; i < node.Children.Count; i++)
        {
            EmitNode(node.Children[i], variable, info, i, node);
        }
        if (info is { Container: DesignContainerKind.None } && node.Children.Count > 0)
        {
            _warnings.Add($"{variable}: {node.Type} cannot hold children.");
        }
        return variable;
    }

    private void EmitAdd(string parent, DesignTypeInfo parentInfo, DesignNode parentNode, DesignNode node, string variable, int index)
    {
        switch (parentInfo.Container)
        {
            case DesignContainerKind.Children:
                Line($"{parent}.Add({variable});");
                break;
            case DesignContainerKind.Content:
                if (index == 0) Line($"{parent}.Content = {variable};");
                else _warnings.Add($"{parent}: {parentInfo.Name} holds a single element; '{variable}' is not added.");
                break;
            case DesignContainerKind.Split:
                if (DesignSlots.SplitPanes(parentNode)[index] is { } second) Line($"{parent}.{(second ? "Second" : "First")} = {variable};");
                else _warnings.Add($"{parent}: a split view holds two elements; '{variable}' is not added.");
                break;
            case DesignContainerKind.Tabs:
                string header = node.Slot ?? "Tab " + (index + 1).ToString(CultureInfo.InvariantCulture);
                Line($"{parent}.Pages.Add(new TabPage({DesignValues.CSharpString(header)}, {variable}));");
                break;
            default:
                _warnings.Add($"{parent}: {parentInfo.Name} cannot hold '{variable}'.");
                break;
        }
    }

    private string NextLocal(string typeName)
    {
        string baseName = char.ToLowerInvariant(typeName[0]) + typeName[1..];
        while (true)
        {
            string candidate = baseName + (++_localCounter).ToString(CultureInfo.InvariantCulture);
            if (_usedNames.Add(candidate)) return candidate;
        }
    }

    /// <summary>Type name as written in generated code: short in the PluginUI namespace, <c>global::</c> qualified otherwise.</summary>
    /// <param name="type">The type.</param>
    /// <returns>The C# type name.</returns>
    public static string TypeName(Type type)
    {
        ArgumentNullException.ThrowIfNull(type);
        string full = (type.FullName ?? type.Name).Replace('+', '.');
        return type.Namespace == "PluginUI" ? full["PluginUI.".Length..] : "global::" + full;
    }

    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    };

    /// <summary>
    /// <c>true</c> if <paramref name="name"/> can name an element field of the generated class: a C# identifier that is
    /// not a member of the class and does not hide a type the generated code uses (element types, value types and
    /// enums of the registry, the class itself).
    /// </summary>
    /// <param name="name">Candidate name.</param>
    /// <returns>Whether it can name a field.</returns>
    public bool IsElementName(string name)
        => IsIdentifier(name) && name != _className && !(_reserved ?? ReservedTypeNames(_registry)).Contains(name);

    /// <summary>Same as <see cref="IsElementName(string)"/> for a registry and a class name.</summary>
    /// <param name="name">Candidate name.</param>
    /// <param name="registry">Registry of the design (default: <see cref="DesignTypeRegistry.Default"/>).</param>
    /// <param name="className">Name of the generated class, or <c>null</c>.</param>
    /// <returns>Whether it can name a field.</returns>
    public static bool IsElementName(string name, DesignTypeRegistry? registry, string? className)
    {
        if (!IsIdentifier(name) || name == className) return false;
        return !ReservedTypeNames(registry ?? DesignTypeRegistry.Default).Contains(name);
    }

    /// <summary>Simple names of the types generated code can mention: hiding one with a field breaks the code.</summary>
    /// <param name="registry">The registry.</param>
    /// <returns>The names.</returns>
    public static IReadOnlySet<string> ReservedTypeNames(DesignTypeRegistry registry)
    {
        ArgumentNullException.ThrowIfNull(registry);
        var names = new HashSet<string>(StringComparer.Ordinal)
        {
            "UIElement", "Canvas", "Size", "SizingMode", "Theme", "Palette", "Typography", "Metrics", "Color", "Thickness", "Point",
            "Rect", "SolidPaint", "LinearGradientPaint", "RadialGradientPaint", "GradientStop", "FilmStrip", "FilmStripSkin",
            "ImageRotarySkin", "SvgRotarySkin", "ImageStateSkin", "ImageSource", "SvgImage", "TextStyle", "VectorStyle", "GridLength",
            "TabPage", "IParameter", "PluginUI", "System", "global",
            // Members of the classes the generated part is combined with (PluginEditorView, scaffolded projects).
            "Host", "Parameters", "Sink", "Controller", "DesignFile", "ConnectKeyboard", "ConfigureHost", "OnAttached", "OnRemoved",
            "BindDesignFields", "_controller", "_parameters", "_bridge",
        };
        // Types of the fields of the values the generated code writes (FontWeight in a TextStyle, ImageFit in a skin…).
        AddPropertyTypes<TextStyle>(names);
        AddPropertyTypes<VectorStyle>(names);
        AddPropertyTypes<Palette>(names);
        AddPropertyTypes<Typography>(names);
        AddPropertyTypes<Metrics>(names);
        AddPropertyTypes<FilmStripDescriptor>(names);
        AddPropertyTypes<FilmStripSkinDescriptor>(names);
        AddPropertyTypes<ImageRotarySkinDescriptor>(names);
        AddPropertyTypes<SvgRotarySkinDescriptor>(names);
        AddPropertyTypes<ImageStateSkinDescriptor>(names);
        foreach (var info in registry.Types)
        {
            names.Add(info.Type.Name);
            foreach (var p in info.Properties)
            {
                var type = Nullable.GetUnderlyingType(p.PropertyType) ?? p.PropertyType;
                names.Add(type.Name);
            }
        }
        return names;
    }

    private static void AddPropertyTypes<[System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers(System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicProperties)] T>(HashSet<string> names)
    {
        foreach (var p in typeof(T).GetProperties(System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Instance))
        {
            names.Add((Nullable.GetUnderlyingType(p.PropertyType) ?? p.PropertyType).Name);
        }
    }

    /// <summary>
    /// Checks the namespace and class name of code generation settings: identifiers that do not hide the types the
    /// generated code uses.
    /// </summary>
    /// <param name="settings">The settings.</param>
    /// <param name="registry">Registry of the design (default: <see cref="DesignTypeRegistry.Default"/>).</param>
    /// <returns><c>null</c> when valid, otherwise the reason (English).</returns>
    public static string? ValidateCodegen(CodegenSettings settings, DesignTypeRegistry? registry = null)
    {
        ArgumentNullException.ThrowIfNull(settings);
        var reserved = ReservedTypeNames(registry ?? DesignTypeRegistry.Default);
        if (!IsNamespace(settings.Namespace)) return $"'{settings.Namespace}' is not a valid C# namespace.";
        if (settings.Namespace.Split('.').FirstOrDefault(reserved.Contains) is { } part) return $"The namespace part '{part}' would hide a type used by the generated code.";
        if (!IsIdentifier(settings.ClassName)) return $"'{settings.ClassName}' is not a valid C# class name.";
        if (reserved.Contains(settings.ClassName)) return $"The class name '{settings.ClassName}' is the name of a type used by the generated code.";
        return null;
    }

    /// <summary><c>true</c> if <paramref name="name"/> is a dotted list of C# identifiers.</summary>
    /// <param name="name">Candidate namespace.</param>
    /// <returns>Whether it can name a namespace.</returns>
    public static bool IsNamespace(string name) => !string.IsNullOrEmpty(name) && name.Split('.').All(IsIdentifier);

    /// <summary><c>true</c> if <paramref name="name"/> is a valid C# identifier (and not a keyword).</summary>
    /// <param name="name">Candidate name.</param>
    /// <returns>Whether it can name a field.</returns>
    public static bool IsIdentifier(string name)
    {
        if (string.IsNullOrEmpty(name) || Keywords.Contains(name)) return false;
        if (!(char.IsLetter(name[0]) || name[0] == '_')) return false;
        foreach (char c in name)
        {
            if (!(char.IsLetterOrDigit(c) || c == '_')) return false;
        }
        return name is not ("BuildDesign" or "Build" or "OnBuilt" or "BindParameter" or "LoadImage" or "LoadSvg" or "DesignSize" or "DesignSizing" or "CreateDesignTheme");
    }

    private void Open()
    {
        Line("{");
        _indent++;
    }

    private void Close()
    {
        _indent--;
        Line("}");
    }

    private void Line(string text = "")
    {
        if (text.Length > 0) _sb.Append(' ', _indent * 4).Append(text);
        _sb.Append('\n');
    }
}
